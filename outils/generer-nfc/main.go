// Commande generer-nfc : écrit internal/jcs/nfc_tables.go, les tables du
// contrôle NFC du JSON canonique (ARCHITECTURE.md §10 ; API.md §1 : une
// chaîne hors NFC est refusée, jamais normalisée), depuis deux fichiers de la
// base de caractères Unicode, de la version de unicode.Version :
//
//	go run ./outils/generer-nfc -ucd <dossier> > internal/jcs/nfc_tables.go
//
// où <dossier> contient UnicodeData.txt et DerivedNormalizationProps.txt
// (https://www.unicode.org/Public/<version>/ucd/). Les tables portent :
// NFC_QC=No (plages), la classe combinatoire canonique non nulle (plages de
// même classe) et les compositions primaires (paires décomposées par une
// décomposition canonique de deux caractères, hors Full_Composition_Exclusion),
// Hangul exclu : sa composition se calcule.
package main

import (
	"bufio"
	"flag"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
	"unicode"
)

func main() {
	dir := flag.String("ucd", "", "dossier de UnicodeData.txt et DerivedNormalizationProps.txt")
	flag.Parse()
	if err := run(*dir, os.Stdout); err != nil {
		fmt.Fprintln(os.Stderr, "generer-nfc :", err)
		os.Exit(1)
	}
}

var propLine = regexp.MustCompile(`^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*(\w+)(?:\s*;\s*(\w+))?`)

func readLines(path string, each func(fields []string) error) error {
	f, err := os.Open(path)
	if err != nil {
		return err
	}
	defer f.Close()
	s := bufio.NewScanner(f)
	for s.Scan() {
		line, _, _ := strings.Cut(s.Text(), "#")
		if line = strings.TrimSpace(line); line == "" {
			continue
		}
		if err := each(strings.Split(line, ";")); err != nil {
			return err
		}
	}
	return s.Err()
}

func run(dir string, out io.Writer) error {
	head, err := os.ReadFile(filepath.Join(dir, "DerivedNormalizationProps.txt"))
	if err != nil {
		return err
	}
	if !strings.Contains(string(head[:min(len(head), 200)]), "-"+unicode.Version+".txt") {
		return fmt.Errorf("DerivedNormalizationProps.txt n'est pas de la version %s", unicode.Version)
	}
	qcNo := map[rune]bool{}
	excluded := map[rune]bool{}
	for _, raw := range strings.Split(string(head), "\n") {
		line, _, _ := strings.Cut(raw, "#")
		m := propLine.FindStringSubmatch(strings.TrimSpace(line))
		if m == nil {
			continue
		}
		lo, _ := strconv.ParseUint(m[1], 16, 32)
		hi := lo
		if m[2] != "" {
			hi, _ = strconv.ParseUint(m[2], 16, 32)
		}
		for r := rune(lo); r <= rune(hi); r++ {
			switch {
			case m[3] == "NFC_QC" && m[4] == "N":
				qcNo[r] = true
			case m[3] == "Full_Composition_Exclusion":
				excluded[r] = true
			}
		}
	}
	ccc := map[rune]int{}
	var pairs [][2]rune
	err = readLines(filepath.Join(dir, "UnicodeData.txt"), func(f []string) error {
		if len(f) < 6 {
			return fmt.Errorf("ligne de UnicodeData.txt illisible : %v", f)
		}
		cp, err := strconv.ParseUint(f[0], 16, 32)
		if err != nil {
			return err
		}
		if c, _ := strconv.Atoi(f[3]); c != 0 {
			ccc[rune(cp)] = c
		}
		d := strings.Fields(f[5])
		if len(d) == 2 && !strings.HasPrefix(d[0], "<") && !excluded[rune(cp)] {
			a, _ := strconv.ParseUint(d[0], 16, 32)
			b, _ := strconv.ParseUint(d[1], 16, 32)
			pairs = append(pairs, [2]rune{rune(a), rune(b)})
		}
		return nil
	})
	if err != nil {
		return err
	}
	sort.Slice(pairs, func(i, j int) bool {
		return pairs[i][0] < pairs[j][0] || pairs[i][0] == pairs[j][0] && pairs[i][1] < pairs[j][1]
	})

	fmt.Fprintf(out, "// Code generated by outils/generer-nfc from the Unicode %s character database; DO NOT EDIT.\n\n", unicode.Version)
	fmt.Fprintln(out, "package jcs")
	fmt.Fprintln(out)
	fmt.Fprintf(out, "const unicodeVersion = %q\n", unicode.Version)
	// Plages NFC_QC=No : début et fin, en hexadécimal sur 5 chiffres.
	var b strings.Builder
	for _, r := range ranges(keys(qcNo), func(rune) int { return 0 }) {
		fmt.Fprintf(&b, "%05x%05x", r[0], r[1])
	}
	writeString(out, "qcNo", "plages NFC_QC=No, début et fin sur 5 chiffres hexadécimaux", b.String())
	b.Reset()
	for _, r := range ranges(keys(ccc), func(c rune) int { return ccc[c] }) {
		fmt.Fprintf(&b, "%05x%05x%02x", r[0], r[1], ccc[r[0]])
	}
	writeString(out, "cccRuns", "plages de même classe combinatoire non nulle : début, fin, classe", b.String())
	b.Reset()
	for _, p := range pairs {
		fmt.Fprintf(&b, "%05x%05x", p[0], p[1])
	}
	writeString(out, "compositions", "compositions primaires triées : premier et second caractère", b.String())
	return nil
}

func keys(m any) []rune {
	var out []rune
	switch m := m.(type) {
	case map[rune]bool:
		for r := range m {
			out = append(out, r)
		}
	case map[rune]int:
		for r := range m {
			out = append(out, r)
		}
	}
	sort.Slice(out, func(i, j int) bool { return out[i] < out[j] })
	return out
}

// ranges regroupe des caractères triés en plages contiguës de même classe.
func ranges(sorted []rune, class func(rune) int) [][2]rune {
	var out [][2]rune
	for _, r := range sorted {
		if n := len(out); n > 0 && out[n-1][1] == r-1 && class(out[n-1][0]) == class(r) {
			out[n-1][1] = r
			continue
		}
		out = append(out, [2]rune{r, r})
	}
	return out
}

func writeString(out io.Writer, name, doc, s string) {
	fmt.Fprintf(out, "\n// %s : %s.\nconst %s = \"\" +\n", name, doc, name)
	const width = 100
	for len(s) > 0 {
		n := min(width, len(s))
		sep := " +"
		if n == len(s) {
			sep = ""
		}
		fmt.Fprintf(out, "\t%q%s\n", s[:n], sep)
		s = s[n:]
	}
}
